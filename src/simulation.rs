//! Explicit deterministic signal generator for software and fault testing.
//!
//! The generator assigns orthogonal synthetic impulse directions to physical
//! positions. That is a test fixture, not a model of real human biomechanics.

use crate::{
    decoder::{CalibrationExample, TapWindow},
    layout::{Finger, Hand, PhysicalPosition, all_slots},
    protocol::{ALL_SENSORS_VALID, SENSOR_COUNT, SensorFrame, SensorReading},
};

const DEFAULT_SAMPLE_COUNT: usize = 16;
const DEFAULT_PERIOD_US: u64 = 5_000;
const TAP_AMPLITUDE: i32 = 12_000;

/// Parameters for one deterministic synthetic session or remount.
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub struct SyntheticConfig {
    hand: Hand,
    controller_id_sha256: [u8; 32],
    boot_id: [u8; 16],
    seed: u64,
    noise_amplitude: i16,
    shared_motion_amplitude: i16,
    remount_per_mille: u16,
    missing_sensor: Option<usize>,
    packet_loss_stride: Option<usize>,
    contact_tail_loss: usize,
    clock_drift_ppm: i32,
    differential_bias_ramp: i16,
    all_sensors_missing: bool,
}

impl SyntheticConfig {
    /// Construct a low-noise synthetic session for one hand.
    #[must_use]
    pub const fn new(hand: Hand, seed: u64) -> Self {
        Self {
            hand,
            controller_id_sha256: match hand {
                Hand::Left => [0x11; 32],
                Hand::Right => [0x22; 32],
            },
            boot_id: match hand {
                Hand::Left => [0x31; 16],
                Hand::Right => [0x32; 16],
            },
            seed,
            noise_amplitude: 8,
            shared_motion_amplitude: 800,
            remount_per_mille: 0,
            missing_sensor: None,
            packet_loss_stride: None,
            contact_tail_loss: 0,
            clock_drift_ppm: 0,
            differential_bias_ramp: 0,
            all_sensors_missing: false,
        }
    }

    /// Override the deterministic synthetic wire identity.
    #[must_use]
    pub const fn with_wire_identity(
        mut self,
        controller_id_sha256: [u8; 32],
        boot_id: [u8; 16],
    ) -> Self {
        self.controller_id_sha256 = controller_id_sha256;
        self.boot_id = boot_id;
        self
    }

    /// Return the hand generated by this fixture configuration.
    #[must_use]
    pub const fn hand(self) -> Hand {
        self.hand
    }

    /// Set independent per-axis integer noise amplitude.
    #[must_use]
    pub const fn with_noise(mut self, amplitude: i16) -> Self {
        self.noise_amplitude = amplitude;
        self
    }

    /// Mix each synthetic position axis into its neighbor to model remount
    /// orientation change. Values above 1,000 are clamped to 1,000.
    #[must_use]
    pub const fn with_remount_per_mille(mut self, amount: u16) -> Self {
        self.remount_per_mille = if amount > 1_000 { 1_000 } else { amount };
        self
    }

    /// Set shared hand-motion amplitude applied to all six sensors.
    #[must_use]
    pub const fn with_shared_motion(mut self, amplitude: i16) -> Self {
        self.shared_motion_amplitude = amplitude;
        self
    }

    /// Mark one canonical sensor invalid in every generated frame.
    #[must_use]
    pub const fn with_missing_sensor(mut self, sensor: usize) -> Self {
        self.missing_sensor = Some(sensor);
        self
    }

    /// Omit each Nth interior frame while retaining the first and contact
    /// frames. Sequence numbers retain their original values so loss is visible.
    #[must_use]
    pub const fn with_packet_loss_stride(mut self, stride: usize) -> Self {
        self.packet_loss_stride = if stride > 1 { Some(stride) } else { None };
        self
    }

    /// Omit the newest contact-bearing samples. The synthetic impulse occupies
    /// the final four frames, so values above four are clamped to four.
    #[must_use]
    pub const fn with_contact_tail_loss(mut self, samples: usize) -> Self {
        self.contact_tail_loss = if samples > 4 { 4 } else { samples };
        self
    }

    /// Apply deterministic device-clock frequency error.
    #[must_use]
    pub const fn with_clock_drift_ppm(mut self, parts_per_million: i32) -> Self {
        self.clock_drift_ppm = parts_per_million;
        self
    }

    /// Add a within-window finger-to-dorsal accelerometer and gyroscope bias
    /// ramp. This is an adversarial synthetic sensor-drift dimension.
    #[must_use]
    pub const fn with_differential_bias_ramp(mut self, amplitude: i16) -> Self {
        self.differential_bias_ramp = amplitude;
        self
    }

    /// Mark all six sensors invalid in every generated frame.
    #[must_use]
    pub const fn with_all_sensors_missing(mut self) -> Self {
        self.all_sensors_missing = true;
        self
    }

    /// Generate prompted examples for all 17 positions on this hand plus idle
    /// negatives. Reserved positions are included so they can abstain safely.
    #[must_use]
    pub fn calibration_examples(
        &self,
        examples_per_position: usize,
        idle_examples: usize,
    ) -> Vec<CalibrationExample> {
        let mut examples = Vec::new();
        for (slot_index, slot) in all_slots()
            .iter()
            .filter(|slot| slot.position.hand == self.hand)
            .enumerate()
        {
            for example_index in 0..examples_per_position {
                let index = slot_index
                    .saturating_mul(examples_per_position)
                    .saturating_add(example_index);
                let trial = u64::try_from(index).unwrap_or(u64::MAX);
                examples.push(CalibrationExample {
                    position: Some(slot.position),
                    window: self.tap_window(slot.position, trial),
                });
            }
        }
        for idle_index in 0..idle_examples {
            examples.push(CalibrationExample {
                position: None,
                window: self.idle_window(
                    10_000_u64.saturating_add(u64::try_from(idle_index).unwrap_or(u64::MAX)),
                ),
            });
        }
        examples
    }

    /// Generate one causal window with a single synthetic position impulse.
    ///
    /// # Panics
    ///
    /// Panics when the position belongs to the other hand. This is a fixture
    /// construction error, not an untrusted runtime input.
    #[must_use]
    pub fn tap_window(&self, position: PhysicalPosition, trial: u64) -> TapWindow {
        assert_eq!(position.hand, self.hand, "synthetic position hand mismatch");
        self.generate_window(&[position], None, trial)
    }

    /// Generate an armed negative with shared hand motion but no finger impulse.
    #[must_use]
    pub fn idle_window(&self, trial: u64) -> TapWindow {
        self.generate_window(&[], None, trial)
    }

    /// Generate a labeled negative containing one unmodeled finger impulse.
    ///
    /// The impulse deliberately overlaps the current key feature space. It is
    /// an adversarial software test that exposes the contact-intent baseline's
    /// boundary; it is not a biomechanical model or a false-activation rate.
    #[must_use]
    pub fn unmodeled_finger_impulse_window(
        &self,
        finger: Finger,
        amplitude: i16,
        trial: u64,
    ) -> TapWindow {
        self.generate_window(&[], Some((finger, i32::from(amplitude))), trial)
    }

    /// Generate two equal concurrent finger impulses.
    ///
    /// # Panics
    ///
    /// Panics when positions belong to another hand or to the same finger.
    #[must_use]
    pub fn simultaneous_window(
        &self,
        first: PhysicalPosition,
        second: PhysicalPosition,
        trial: u64,
    ) -> TapWindow {
        assert_eq!(
            first.hand, self.hand,
            "first synthetic position hand mismatch"
        );
        assert_eq!(
            second.hand, self.hand,
            "second synthetic position hand mismatch"
        );
        assert_ne!(
            first.finger, second.finger,
            "simultaneous fixture needs two fingers"
        );
        self.generate_window(&[first, second], None, trial)
    }

    fn generate_window(
        &self,
        positions: &[PhysicalPosition],
        unmodeled_impulse: Option<(Finger, i32)>,
        trial: u64,
    ) -> TapWindow {
        let position_seed = positions.iter().fold(0_u64, |seed, position| {
            seed ^ (u64::from(position.slot) << (position.finger.sensor_index() * 8))
        });
        let mut random =
            SplitMix64::new(self.seed ^ trial.wrapping_mul(0x9e37_79b9_7f4a_7c15) ^ position_seed);
        let base_time = trial.saturating_mul(1_000_000);
        let trial_bytes = trial.to_le_bytes();
        let trial_low = u32::from_le_bytes([
            trial_bytes[0],
            trial_bytes[1],
            trial_bytes[2],
            trial_bytes[3],
        ]);
        let sequence_base = trial_low.wrapping_mul(16);
        let period_numerator = i64::try_from(DEFAULT_PERIOD_US).expect("default period fits i64")
            * (1_000_000_i64 + i64::from(self.clock_drift_ppm));
        let period_us = u64::try_from((period_numerator / 1_000_000).max(1)).unwrap_or(1);
        let mut frames = Vec::with_capacity(DEFAULT_SAMPLE_COUNT);

        for sample_index in 0..DEFAULT_SAMPLE_COUNT {
            if self.packet_loss_stride.is_some_and(|stride| {
                sample_index > 0
                    && sample_index + 1 < DEFAULT_SAMPLE_COUNT
                    && sample_index % stride == 0
            }) {
                continue;
            }
            if sample_index >= DEFAULT_SAMPLE_COUNT.saturating_sub(self.contact_tail_loss.min(4)) {
                continue;
            }
            let shared = shared_vector(
                sample_index,
                DEFAULT_SAMPLE_COUNT,
                i32::from(self.shared_motion_amplitude),
            );
            let mut sensors = [SensorReading::default(); SENSOR_COUNT];
            for sensor in &mut sensors {
                let mut vector = shared;
                for value in &mut vector {
                    *value += random.symmetric(i32::from(self.noise_amplitude));
                }
                *sensor = reading_from_vector(vector);
            }

            let bias = i32::from(self.differential_bias_ramp)
                * i32::try_from(sample_index).expect("sample index fits i32")
                / i32::try_from(DEFAULT_SAMPLE_COUNT - 1).expect("sample count fits i32");
            for sensor in &mut sensors[..5] {
                add_axis(sensor, 0, bias);
                add_axis(sensor, 3, bias / 2);
            }

            for position in positions {
                let waveform = contact_waveform(sample_index, DEFAULT_SAMPLE_COUNT);
                if waveform == 0 {
                    continue;
                }
                let sensor = position.finger.sensor_index();
                let primary_axis = usize::from(position.slot);
                let neighbor_axis = (primary_axis + 1) % 6;
                let remount = i32::from(self.remount_per_mille);
                let primary = TAP_AMPLITUDE * waveform * (1_000 - remount) / 4_000;
                let neighbor = TAP_AMPLITUDE * waveform * remount / 4_000;
                add_axis(&mut sensors[sensor], primary_axis, primary);
                add_axis(&mut sensors[sensor], neighbor_axis, neighbor);
            }

            if let Some((finger, amplitude)) = unmodeled_impulse {
                let waveform = contact_waveform(sample_index, DEFAULT_SAMPLE_COUNT);
                let value = amplitude * waveform / 4;
                add_axis(&mut sensors[finger.sensor_index()], 0, value);
            }

            let valid_sensor_mask = if self.all_sensors_missing {
                0
            } else {
                self.missing_sensor.map_or(ALL_SENSORS_VALID, |sensor| {
                    if sensor < SENSOR_COUNT {
                        ALL_SENSORS_VALID & !(1_u8 << sensor)
                    } else {
                        ALL_SENSORS_VALID
                    }
                })
            };
            frames.push(SensorFrame {
                hand: self.hand,
                controller_id_sha256: self.controller_id_sha256,
                boot_id: self.boot_id,
                flags: 0,
                valid_sensor_mask,
                sequence: sequence_base.wrapping_add(
                    u32::try_from(sample_index).expect("window sample index fits u32"),
                ),
                device_time_us: base_time
                    + u64::try_from(sample_index).expect("window sample index fits u64")
                        * period_us,
                sensors,
            });
        }

        TapWindow::new(frames).expect("synthetic frames form a valid causal window")
    }
}

fn shared_vector(sample: usize, sample_count: usize, amplitude: i32) -> [i32; 6] {
    let sample = i32::try_from(sample).expect("synthetic window length fits i32");
    let sample_count = i32::try_from(sample_count).expect("synthetic window length fits i32");
    let centered = sample * 2 - (sample_count - 1);
    let wave = centered * amplitude / sample_count;
    [wave, -wave / 2, wave / 3, -wave / 4, wave / 5, -wave / 6]
}

fn contact_waveform(sample: usize, sample_count: usize) -> i32 {
    match sample_count.saturating_sub(sample) {
        4 => 1,
        3 => 2,
        2 => 3,
        1 => 4,
        _ => 0,
    }
}

fn reading_from_vector(vector: [i32; 6]) -> SensorReading {
    SensorReading {
        acceleration: [
            clamp_i16(vector[0]),
            clamp_i16(vector[1]),
            clamp_i16(vector[2]),
        ],
        angular_velocity: [
            clamp_i16(vector[3]),
            clamp_i16(vector[4]),
            clamp_i16(vector[5]),
        ],
        sample_time_offset_us: 0,
    }
}

fn add_axis(reading: &mut SensorReading, axis: usize, value: i32) {
    let target = if axis < 3 {
        &mut reading.acceleration[axis]
    } else {
        &mut reading.angular_velocity[axis - 3]
    };
    *target = clamp_i16(i32::from(*target) + value);
}

fn clamp_i16(value: i32) -> i16 {
    i16::try_from(value.clamp(i32::from(i16::MIN), i32::from(i16::MAX)))
        .expect("clamped signal fits i16")
}

#[derive(Clone, Copy, Debug)]
struct SplitMix64 {
    state: u64,
}

impl SplitMix64 {
    const fn new(seed: u64) -> Self {
        Self { state: seed }
    }

    fn next(&mut self) -> u64 {
        self.state = self.state.wrapping_add(0x9e37_79b9_7f4a_7c15);
        let mut value = self.state;
        value = (value ^ (value >> 30)).wrapping_mul(0xbf58_476d_1ce4_e5b9);
        value = (value ^ (value >> 27)).wrapping_mul(0x94d0_49bb_1331_11eb);
        value ^ (value >> 31)
    }

    fn symmetric(&mut self, amplitude: i32) -> i32 {
        let amplitude = amplitude.abs();
        if amplitude == 0 {
            return 0;
        }
        let width = u64::try_from(amplitude)
            .expect("i32 amplitude fits u64")
            .saturating_mul(2)
            + 1;
        i32::try_from(self.next() % width).expect("noise width fits i32") - amplitude
    }
}
